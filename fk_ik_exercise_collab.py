# Now since we obtained the full Jacobian matrix we can compute the IK
# main simplfied idea: position = J x angle, therefore in IK
# angle = J^{-1} x position

def solve_ik_position(target_pos, theta_init, dh_matrix_fn, alpha_rad, a, d, max_iters=100, tol=1e-3, lr=0.5):
    theta = theta_init.clone()
    device = theta.device

    for iteration in range(max_iters):
        # Forward Kinematics: Build cumulative transforms T_01 ... T_06
        t_cumul = []
        T_curr = torch.eye(4, device=device)

        # Compute the whole T and stored in t_cumul
        for i in range(6):
            T_i = dh_matrix_fn(theta[i], alpha_rad[i], a[i], d[i])
            T_curr = T_curr @ T_i
            t_cumul.append(T_curr)

        # Extract current end-effector position (P_06)
        # [DEBUG LOG]
        if iteration == 1:
            print("T_06:")
            print(torch.round(t_cumul[5], decimals=4))

        P_06 = t_cumul[5][:3, 3]  # Shape: (3,)

        # Calculate position error vector
        error = target_pos - P_06  # Shape: (3,), this is the (O_i - P_06)
        error_norm = torch.norm(error)

        # Stop if error is within acceptable tolerance
        if error_norm < tol:
            print(f"Converged in {iteration} iterations!")
            return theta, True

        # Build the 3x6 Position-Only Jacobian
        j_cols = []
        for i in range(6):
            if i == 0:
                z_i = torch.tensor([0.0, 0.0, 1.0], device=device)
                P_i = torch.tensor([0.0, 0.0, 0.0], device=device)
            else:
                z_i = t_cumul[i - 1][:3, 2]
                P_i = t_cumul[i - 1][:3, 3]

            # Linear velocity component: z_i x (P_06 - P_i)
            J_v = torch.linalg.cross(z_i, P_06 - P_i)  # Shape: (3,)
            j_cols.append(J_v)

        J_pos = torch.stack(j_cols, dim=1)  # Shape: (3, 6)

        # Compute Pseudo-Inverse J^dagger
        J_pinv = torch.linalg.pinv(J_pos)   # Shape: (6, 3)

        # Update joint angles: theta_new = theta + lr * (J_pinv @ error)
        d_theta = J_pinv @ error            # Shape: (6,)
        theta = theta + lr * d_theta



    print("Reached max iterations without full convergence.")
    return theta, False

# Hardcode the target position (x, y, z)
target_xyz = torch.tensor([0.4, 0.2, 0.5], device=device)

# Hardcode your initial guess for joint angles
theta_start = torch.zeros(6, device=device)

# 3. Run the IK solver
theta_solution, success = solve_ik_position(
    target_pos=target_xyz,
    theta_init=theta_start,
    dh_matrix_fn=dh_matrix,
    alpha_rad=alpha_rad,
    a=a,
    d=d
)

