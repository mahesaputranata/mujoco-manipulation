# 1. First Pass: Compute all Cumulative Transforms T_0i
t_cumul = []
T_curr = torch.eye(4, device=theta_home_rad.device)

for i in range(6):
    T_i = dh_matrix(theta_home_rad[i], alpha_rad[i], a[i], d[i])
    T_curr = T_curr @ T_i        # Multiply in correct order: T_0i = T_0{i-1} @ T_{i-1}i
    t_cumul.append(T_curr)

# Extract End-Effector Position P_06 (4th column of final matrix)
P_06 = t_cumul[5][:3, 3]

# 2. Second Pass: Compute Jacobian Columns
j_cols = []

for i in range(6):
    if i == 0:
        # Base frame origin & Z-axis for Joint 1
        z_i = torch.tensor([0.0, 0.0, 1.0], device=P_06.device)
        P_i = torch.tensor([0.0, 0.0, 0.0], device=P_06.device)
    else:
        # Origin & Z-axis from frame (i-1) for Joint i+1
        z_i = t_cumul[i - 1][:3, 2]  # 3rd column = Z-axis (1D vector, shape [3])
        P_i = t_cumul[i - 1][:3, 3]  # 4th column = Origin (1D vector, shape [3])

    # Linear Velocity Part: z_i x (P_06 - P_i)
    J_v = torch.linalg.cross(z_i, P_06 - P_i)  # Shape: [3]

    # Angular Velocity Part: z_i
    J_w = z_i                                  # Shape: [3]

    # Combine into a full 6x1 column for Joint i
    J_i = torch.cat([J_v, J_w], dim=0)         # Shape: [6]
    j_cols.append(J_i)

# 3. Stack columns horizontally along dim=1 to form full 6x6 Matrix
J_matr = torch.stack(j_cols, dim=1)            # Shape: torch.Size([6, 6])

