## compute the DH matrix

def dh_matrix(theta_i, alpha_i, a_i, d_i):
  ct = torch.cos(theta_i)
  st = torch.sin(theta_i)
  ca = torch.cos(alpha_i)
  sa = torch.sin(alpha_i)

  T = torch.tensor([
    [ct, -st*ca, st*sa, a_i*ct],
    [st, ct*ca, -ct*sa, a_i*st],
    [0, sa, ca, d_i],
    [0, 0, 0, 1]
  ], device=device)
  return T

